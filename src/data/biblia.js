const PLANO_ATIVO_KEY   = 'biblia_plano_ativo';
const CONCLUIDOS_KEY    = 'biblia_planos_concluidos';
const LEGADO_PROGRESSO_KEY = 'biblia_progresso'; // chave antiga, usada antes de existir mais de um plano

function progressoKey(planoId) {
  return `biblia_progresso_${planoId}`;
}

export function loadPlanoAtivoId() {
  const salvo = localStorage.getItem(PLANO_ATIVO_KEY);
  return PLANOS.some(p => p.id === salvo) ? salvo : PLANOS[0].id;
}

export function savePlanoAtivoId(planoId) {
  localStorage.setItem(PLANO_ATIVO_KEY, planoId);
}

// Migra o progresso salvo na chave antiga (de quando só existia um plano) pra
// dentro do primeiro plano, na primeira vez que alguém carrega o progresso dele.
export function loadProgresso(planoId) {
  try {
    const salvo = localStorage.getItem(progressoKey(planoId));
    if (salvo) return JSON.parse(salvo) || [];
    if (planoId === PLANOS[0].id) {
      const legado = JSON.parse(localStorage.getItem(LEGADO_PROGRESSO_KEY)) || [];
      if (legado.length) localStorage.setItem(progressoKey(planoId), JSON.stringify(legado));
      return legado;
    }
    return [];
  } catch { return []; }
}

export function saveProgresso(planoId, dias) {
  localStorage.setItem(progressoKey(planoId), JSON.stringify(dias));
}

export function loadPlanosConcluidos() {
  try { return JSON.parse(localStorage.getItem(CONCLUIDOS_KEY)) || []; }
  catch { return []; }
}

export function marcarPlanoConcluido(planoId) {
  const atuais = loadPlanosConcluidos();
  if (atuais.includes(planoId)) return atuais;
  const novos = [...atuais, planoId];
  localStorage.setItem(CONCLUIDOS_KEY, JSON.stringify(novos));
  return novos;
}

// Primeiro plano ainda não concluído, diferente do atual — usado pra sugerir
// "o que ler a seguir" quando a pessoa termina um plano.
export function proximoPlanoSugerido(planoAtualId, concluidos) {
  return PLANOS.find(p => p.id !== planoAtualId && !concluidos.includes(p.id)) || null;
}
